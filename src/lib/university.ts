export type ReqLevel = "مرتفع" | "متوسط" | "منخفض" | "يفضّل مرتفع";
export type MajorCategory = "صحي" | "هندسي" | "حاسب" | "إداري" | "قانوني" | "عام";

/* مسار القبول — يحدّد أي معادلة موزونة تنطبق */
export type AdmissionTrack = "علمي" | "إنساني";

/* معادلة الموزونة: أوزان مئوية على الثانوية + القدرات + التحصيلي (مجموعها 100) */
export interface WeightedFormula {
  id: string;          // معرّف فريد داخل الجامعة
  label: string;       // وصف للعرض: «علمي» / «إنساني» / «علمي - طالبات» ...
  track: AdmissionTrack;
  highschool: number;  // وزن الثانوية (نسبة مئوية 0–100)
  qudurat: number;     // وزن القدرات
  tahsili: number;     // وزن التحصيلي
  note?: string;       // ملاحظة إضافية (شرط لغة إنجليزية، مقابلة...)
}

export interface UniversityOption {
  id: string;
  name: string;
  region?: string;
  kind?: "حكومية" | "أهلية";
  formulas?: WeightedFormula[];   // معادلات الموزونة الرسمية (إن توفّرت)
  colleges?: string[];            // الكليات المتاحة
  admissionNote?: string;         // ملاحظة قبول عامة (للأهلية غالباً)
  /* ── حقول ملف الجامعة (كلها اختيارية وغير كاسرة؛ الغياب مقصود عند عدم اليقين) ── */
  description?: string;           // نبذة قصيرة دائمة عامة وآمنة
  city?: string;                  // المدينة (غالباً = عاصمة المنطقة)
  foundedYear?: number;           // سنة التأسيس الميلادية (للمعروفة فقط)
  website?: string;               // الموقع الرسمي https ونطاق ‎.edu.sa (للمعروفة فقط)
  pros?: string[];                // مميزات نوعية عامة آمنة
  cons?: string[];                // اعتبارات محايدة إرشادية (لا عيوب تشهيرية)
  strengths?: string[];           // مجالات تميز معروفة (حيث تُعرف)
  /* ── التصنيف العالمي (QS) ── يُملأ للمؤكَّد فقط، ويُذكر إصداره دائماً لأنه يتغيّر سنوياً.
     جامعةٌ بلا رقمٍ موثّق تبقى بلا حقل، فلا تظهر رقاقةٌ إطلاقاً — لا صفرٌ ولا تقدير.
     QS ينشر المراكز المتأخّرة كنطاقات (٧٤١–٧٥٠)، فـ`qsRank` هو الحدّ الأدنى
     و`qsRankTo` الحدّ الأعلى عند وجوده. عرضُ نطاقٍ كرقمٍ واحد تزييفٌ لدقّةٍ لا نملكها. */
  qsRank?: number;                // الترتيب العالمي في QS (أو بداية النطاق)
  qsRankTo?: number;              // نهاية النطاق — يغيب للمراكز المفردة
  qsYear?: number;                // سنة إصدار التصنيف (لا سنة القياس)
  /* الترتيب العربي (Times Higher Education) — من دليل المالك، للموثّق فقط */
  arabRank?: number;              // مركزٌ عربيٌّ محدّد
  arabTopN?: number;              // أو «ضمن أفضل N عربياً» حين لا يُنشر المركز المفرد
}

/** نصُّ ترتيب QS جاهزاً للعرض: «٦٣» أو «٧٤١–٧٥٠». فارغٌ حين لا ترتيبَ موثّق. */
export function qsRankText(u: Pick<UniversityOption, "qsRank" | "qsRankTo">, fmt: (x: number) => string): string {
  if (u.qsRank == null) return "";
  return u.qsRankTo != null ? `${fmt(u.qsRank)}–${fmt(u.qsRankTo)}` : fmt(u.qsRank);
}

/** نصُّ الترتيب العربي: «الـ٤ عربياً» أو «ضمن أفضل ١٠ عربياً». فارغٌ حين لا بيانات. */
export function arabRankText(u: Pick<UniversityOption, "arabRank" | "arabTopN">, fmt: (x: number) => string): string {
  if (u.arabRank != null) return `الـ${fmt(u.arabRank)} عربياً`;
  if (u.arabTopN != null) return `ضمن أفضل ${fmt(u.arabTopN)} عربياً`;
  return "";
}

