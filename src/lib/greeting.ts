/* ── ترحيبُ دويرب في «مساري» ──
   كان سطراً واحداً لا يتغيّر أبداً. صار يُنتقى كتحيّة الرئيسية — الاسمُ يُركَّب
   في الوسط فيصلح لمن سمّى نفسه ولمن لم يفعل. */
export function duwairbGreeting(name: string | undefined, hour: number, r: number): string {
  const h = helloFor(hour, r);
  if (!name) {
    /* بلا اسمٍ: نأخذ صدرَ التحيّة ونُسقط ما بعد الاسم، وننظّف أداةَ النداء */
    return h.before.replace(/[،\s]+$/, "").replace(/\s*(يا|بـ)$/, "").trim();
  }
  return `${h.before}${name}${h.after}`;
}
