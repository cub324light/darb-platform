/** رقمُ اليوم في السنة — مصدرُ الدوران، ويُحسب خارج المحرّك من تاريخٍ حقيقيّ. */
export const dayIndexOf = (year: number, month: number, day: number): number =>
  Math.floor(Date.UTC(year, month, day) / 86400000);
