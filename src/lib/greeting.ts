/** انتقاءٌ من قائمةٍ برقمٍ عشوائيّ `r ∈ [0,1)` — يقبل الشاذّ ولا ينكسر. */
const pick = <T,>(pool: T[], r: number): T => {
  const x = Number.isFinite(r) ? Math.abs(r) % 1 : 0;
  return pool[Math.min(pool.length - 1, Math.floor(x * pool.length))];
};

/**
 * تحيّةُ اللحظة: صباحٌ ٥–١١، مساءٌ ١٧–٢٠، وما بقي ليل. وتحيّاتُ «كل وقت»
 * مخلوطةٌ مع تحيّة الوقت، فيسمع الطالبُ «صباح الخير» و«هلا والله» كلتيهما صباحاً.
 */
export function helloFor(hour: number, r: number): Hello {
  const h = ((hour % 24) + 24) % 24;
  const timed = h >= 5 && h < 12 ? MORNING : h >= 17 && h < 21 ? EVENING : h >= 21 || h < 5 ? NIGHT : [];
  return pick([...timed, ...ANY], r);
}

