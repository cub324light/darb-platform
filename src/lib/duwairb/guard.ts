/** جوابٌ نهائيّ نافع حين يُصرّ النموذج على الرفض — سؤالٌ لا جدار. */
export function fallbackAsk(prompt: string): string {
  const p = prompt.trim();
  const hasExam = /قدرات|تحصيلي|تحصيلى|ستيب|توفل|ايلتس|آيلتس|أرامكو|اراكمو|CPC/i.test(p);
  const hasTime = /ساعة|ساعات|دقيقة|صباح|مساء|ليل|يوم|أسبوع|اسبوع|شهر/.test(p);

  const need: string[] = [];
  if (!hasExam) need.push("لأي اختبارٍ أو مادة؟");
  if (!hasTime) need.push("وكم ساعةً متاحةً عندك في اليوم؟");

  if (need.length === 0) {
    return "تمام — أعطني تاريخ اختبارك أو المدّة المتبقّية وأبني لك الجدول فوراً.";
  }
  return `أبني لك الجدول الآن — ${need.join(" ")}`;
}
