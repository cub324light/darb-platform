/* ═══════════ حارسُ ردّ دويرب — نقيٌّ ١٠٠٪ ═══════════
   العطل: الطالب يكتب «عطني جدول دراسي جاهز لليوم» — وهو حرفياً وظيفةُ دويرب —
   فيردّ النموذج بجملة الرفض «أنا دويرب المختص بإعداد الجداول… فقط». شدّدنا
   التعليمات فخفّ الأمر ولم ينتهِ، لأن التعليمات **رجاءٌ** للنموذج لا ضمان.

   فالضمانُ هنا: نفحص الردّ قبل أن يصل الطالب. إن كان الطلبُ تخطيطاً والردُّ
   رفضاً، فالردُّ خطأٌ يقيناً — لا نُمرّره. نُعيد المحاولة مرّةً بتوجيهٍ أشدّ،
   وإن أصرّ النموذج أعطينا الطالبَ سؤالاً مفيداً بدل جدارٍ مسدود.

   نقيّ: نصٌّ داخلٌ ونصٌّ خارج. لا شبكة ولا window ولا Date. */

/** بصمةُ جملة الرفض — نطابق جوهرَها لا حرفَها، فتعديلُ صياغةٍ لا يُفلتها. */
const REFUSAL_MARKS = [
  /المختص\s+بإعداد\s+الجداول/,
  /مختصٌّ?\s+بإعداد\s+الجداول/,
  /الجداول\s+والخطط\s+الدراسية\s+فقط/,
];

export function isRefusalText(text: string): boolean {
  const t = text.trim();
  /* الرفضُ ردٌّ قصيرٌ مقطوع. لو جاءت العبارةُ داخل جدولٍ مطوّل فليست رفضاً. */
  if (t.length > 400) return false;
  return REFUSAL_MARKS.some((r) => r.test(t));
}

/* كلماتٌ تدلّ على طلب تخطيطٍ أو مذاكرة — يكفي واحدة. جُمعت من عبارات الطلاب
   الحقيقية في أزرار درب السريعة ومن صياغاتهم العامّية. */
const PLANNING_WORDS = [
  "جدول", "جداول", "خطة", "خطه", "خطط", "برنامج",
  "رتب", "رتّب", "نظم", "نظّم", "وزّع", "وزع",
  "مذاكرة", "مذاكره", "اذاكر", "أذاكر", "ذاكر", "دراسة", "دراسه",
  "وقت", "ساعات", "ساعة", "يومي", "أسبوعي", "اسبوعي",
  /* أزرارُ درب السريعة تصف **الفراغ والانشغال** بلا ذكر كلمة «جدول» —
     «مشغول الصباح (6-12)» طلبُ جدولٍ وإن لم يقلها. */
  "مشغول", "فاضي", "فراغ", "صباح", "مساء", "ليل", "بدون مدرسة",
  "ابدأ", "أبدأ", "من وين", "من أين",
  "قدرات", "تحصيلي", "ستيب", "تحصيلى",
  "اختبار", "الاختبار", "مراجعة", "مراجعه",
];

/** هل الطلبُ في نطاق دويرب (تخطيطٌ/مذاكرة)؟ */
export function isPlanningRequest(prompt: string): boolean {
  const p = prompt.trim();
  if (!p) return false;
  return PLANNING_WORDS.some((w) => p.includes(w));
}

/** هل هذا الردُّ خطأٌ يقيناً — رفضٌ في وجه طلبٍ مشروع؟ */
export const isWrongRefusal = (prompt: string, reply: string): boolean =>
  isRefusalText(reply) && isPlanningRequest(prompt);

