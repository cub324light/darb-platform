/** كليات جامعةٍ بعينها — فارغةٌ حين لا نعرفها (لا اختراع). */
export const collegesAt = (uniId?: string): UniCollege[] =>
  (uniId ? UNIVERSITY_COLLEGES[uniId] : undefined) ?? [];

/** تخصصات كليةٍ بعينها داخل جامعة. */
export function majorsIn(uniId: string | undefined, collegeName: string): UniMajor[] {
  return collegesAt(uniId).find((k) => k.name === collegeName)?.majors ?? [];
}

/** كل التخصصات الدقيقة في جامعةٍ مسطَّحةً (للبحث والتحقّق). */
export const allMajorsAt = (uniId?: string): UniMajor[] =>
  collegesAt(uniId).flatMap((k) => k.majors);

/** الكلية التي ينتمي إليها تخصّصٌ دقيق (لاستعادة الاختيار المحفوظ). */
export function collegeOfMajor(uniId: string | undefined, majorName: string): string | undefined {
  return collegesAt(uniId).find((k) => k.majors.some((m) => m.name === majorName))?.name;
}

/** التصنيف الخشن (`MAJORS`) لتخصّصٍ دقيق — يغيب حين لا يقابله تصنيف. */
export function categoryOfMajor(uniId: string | undefined, majorName: string): string | undefined {
  return allMajorsAt(uniId).find((m) => m.name === majorName)?.categoryId;
}

/** هل نعرف كليات هذه الجامعة؟ */
export const hasColleges = (uniId?: string): boolean =>
  !!uniId && UNIVERSITY_COLLEGES[uniId] !== undefined;

