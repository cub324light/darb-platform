/* ════════ اشتقاق فئة التخصص (نقي) — تُستهلك في الصفحة بتهيئة كسولة ════════
   الأولوية: التخصص المنظَّم (goals.majorId → فئته) ثم نوع المسار الجامعي
   (user.trackType إن كان فئة صالحة) وإلا «عام» كأكثر تحفّظاً. */
export function resolveCategory(majorId?: string | null, trackType?: string | null): MajorCategory {
  const m = findMajor(majorId ?? undefined);
  if (m) return m.category;
  if (trackType && (CAREER_CATEGORIES as string[]).includes(trackType)) {
    return trackType as MajorCategory;
  }
  return "عام";
}
