/* تطبيع الصف (من ملف الطالب) إلى مفتاح المنهج. الأول/غيره → لا منهج (undefined). */
function gradeKey(grade?: string): GradeKey | undefined {
  if (grade === "ثاني ثانوي") return "ثاني";
  if (grade === "ثالث ثانوي") return "ثالث";
  return undefined;
}

/* تطبيع الفصل (academicTerm: first/second/summer) إلى فصلٍ دراسي. */
function semKey(term?: string): SemKey {
  return term === "second" ? "s2" : term === "summer" ? "s3" : "s1";
}

/** مواد الطالب الحالية حسب المسار + الصف + الفصل — فارغةٌ إن لم يكن ثاني/ثالث أو بلا مسار. */
export function subjectsFor(track?: AcademicTrack | null, grade?: string, term?: string): string[] {
  if (!track) return [];
  const g = gradeKey(grade);
  if (!g) return [];
  return CURRICULUM[track]?.[g]?.[semKey(term)] ?? [];
}

